// Generates TypeScript from the Rust side's JSON Schemas so the UI and the shell can't drift
// (ui/spec.md §23.3):
//   src/generated/bridge.schema.json  ← apps/windows/src/protocol.rs (bridge_schema_is_current test)
//   schema/cutproj.schema.json        ← the core's project model (`video-studio schema`)
import { compile } from 'json-schema-to-typescript';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const out = resolve(here, '../src/generated');
mkdirSync(out, { recursive: true });

const banner = '/* Generated by scripts/gen-types.mjs from a JSON Schema written by the Rust code. Do not edit. */';
const jobs = [
  [resolve(out, 'bridge.schema.json'), resolve(out, 'bridge.ts'), 'Bridge'],
  [resolve(here, '../../../../schema/cutproj.schema.json'), resolve(out, 'project.ts'), 'Project'],
];
for (const [src, dest, name] of jobs) {
  const schema = JSON.parse(readFileSync(src, 'utf8'));
  // schemars writes `$defs`; the generator wants a title for the root type.
  schema.title = name;
  const ts = await compile(schema, name, {
    bannerComment: banner,
    additionalProperties: false,
    strictIndexSignatures: false,
    unreachableDefinitions: true,
    format: false,
    style: { singleQuote: true },
  });
  writeFileSync(dest, ts);
  console.log(`wrote ${dest}`);
}
