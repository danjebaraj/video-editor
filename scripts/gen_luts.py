#!/usr/bin/env python3
"""Generate the bundled .cube LUTs (17^3). Our own math, released CC0 with this repo.
Usage: python3 scripts/gen_luts.py assets/luts"""
import math, sys, os

N = 17

def clamp(v): return max(0.0, min(1.0, v))

def smooth_s(v, k):  # filmic S-curve around 0.5
    return clamp(0.5 + (v - 0.5) * (1 + k) - k * 4 * (v - 0.5) ** 3)

def luma(r, g, b): return 0.2126 * r + 0.7152 * g + 0.0722 * b

def sat(r, g, b, s):
    y = luma(r, g, b)
    return tuple(clamp(y + (c - y) * s) for c in (r, g, b))

def warm_film(r, g, b):
    r, g, b = smooth_s(r, 0.18), smooth_s(g, 0.15), smooth_s(b, 0.12)
    r, g, b = clamp(r * 1.06 + 0.02), clamp(g * 1.01 + 0.01), clamp(b * 0.90 + 0.03)  # warm + lifted blacks
    return sat(r, g, b, 0.9)

def cool_clean(r, g, b):
    r, g, b = smooth_s(r, 0.08), smooth_s(g, 0.08), smooth_s(b, 0.08)
    return sat(clamp(r * 0.95), clamp(g * 1.0), clamp(b * 1.07 + 0.01), 1.05)

def punchy(r, g, b):
    r, g, b = smooth_s(r, 0.3), smooth_s(g, 0.3), smooth_s(b, 0.3)
    return sat(r, g, b, 1.3)

def bw_contrast(r, g, b):
    y = smooth_s(luma(r, g, b), 0.45)
    return (y, y, y)

def teal_orange(r, g, b):
    y = luma(r, g, b)
    # shadows toward teal, highlights toward orange
    t = clamp((y - 0.2) / 0.6)
    tr, tg = (0.0, 0.06, 0.08), (0.09, 0.03, -0.06)
    r += tr[0] * (1 - t) + tg[0] * t
    g += tr[1] * (1 - t) + tg[1] * t
    b += tr[2] * (1 - t) + tg[2] * t
    r, g, b = smooth_s(clamp(r), 0.15), smooth_s(clamp(g), 0.15), smooth_s(clamp(b), 0.15)
    return sat(r, g, b, 1.1)

def write(path, fn, title):
    with open(path, "w") as f:
        f.write(f'TITLE "{title}"\n# generated by scripts/gen_luts.py (CC0)\nLUT_3D_SIZE {N}\n')
        for bi in range(N):
            for gi in range(N):
                for ri in range(N):
                    r, g, b = ri / (N - 1), gi / (N - 1), bi / (N - 1)
                    o = fn(r, g, b)
                    f.write("%.6f %.6f %.6f\n" % tuple(clamp(v) for v in o))

out = sys.argv[1] if len(sys.argv) > 1 else "assets/luts"
os.makedirs(out, exist_ok=True)
for name, fn in [("warm_film", warm_film), ("cool_clean", cool_clean), ("punchy", punchy), ("bw_contrast", bw_contrast), ("teal_orange", teal_orange)]:
    write(os.path.join(out, name + ".cube"), fn, name)
