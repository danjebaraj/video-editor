#!/usr/bin/env bash
# Build a release `cutline` into ./bin, ready to run from anywhere:
#   bin/cutline              release binary (features: $CUTLINE_FEATURES, default onnx)
#   bin/assets/              fonts, LUTs, templates (found next to the binary)
#   bin/CUTLINE_MANUAL.md    manual for Claude, generated from this binary
#   bin/project.schema.json  project JSON Schema from this binary
# Tools (ffmpeg, models, Chrome) come from the repo's .cutline-home, which the binary finds
# by searching up from bin/ (or CUTLINE_HOME).
#
# Usage: scripts/build-bin.sh
# The old bin/ is replaced only after the build and manual succeed.
set -euo pipefail
cd "$(dirname "$0")/.."
ROOT=$(pwd)
FEATURES="${CUTLINE_FEATURES:-onnx}"
EXE=cutline
case "$(uname -s)" in MINGW*|MSYS*|CYGWIN*) EXE=cutline.exe ;; esac

echo "› cargo build --release -p cutline-cli --features $FEATURES"
cargo build --release -p cutline-cli --features "$FEATURES"

STAGE="$ROOT/bin.new"
rm -rf "$STAGE"
mkdir -p "$STAGE"
cp "target/release/$EXE" "$STAGE/"
cp -R assets "$STAGE/assets"
B="$STAGE/$EXE"

# --- manual -------------------------------------------------------------------------------
# Nest an included doc under our section: drop its title (H1) and demote the other headings
# one level, outside code fences.
demote() {
  awk '/^```/ { fence = !fence }
       !fence && /^# / { next }
       { if (!fence && /^#/) print "#" $0; else print }' "$@"
}

# `cutline <args> --help` for a command and, recursively, its subcommands.
help_section() { # $1 = heading level ("###"), rest = command words
  local level=$1; shift
  printf '%s `cutline %s`\n\n```text\n' "$level" "$*"
  "$B" "$@" --help
  printf '```\n\n'
  local subs
  subs=$("$B" "$@" --help | awk '/^Commands:/ { on = 1; next } /^[^ ]/ { on = 0 } on && NF { print $1 }' | grep -v '^help$' || true)
  for s in $subs; do help_section "$level#" "$@" "$s"; done
}

VERSION=$("$B" --version)
COMMIT=$(git rev-parse --short HEAD 2>/dev/null || echo unknown)
if [ -n "$(git status --porcelain --untracked-files=no 2>/dev/null)" ]; then COMMIT="$COMMIT (with uncommitted changes)"; fi
"$B" schema > "$STAGE/project.schema.json"

M="$STAGE/CUTLINE_MANUAL.md"
{
  printf '# cutline manual for Claude\n\n'
  printf 'Generated by `scripts/build-bin.sh` from the binary next to this file, so it matches it\n'
  printf 'exactly. Rebuild with that script after pulling changes.\n\n'
  printf -- '- Version: %s\n' "$VERSION"
  printf -- '- Commit: %s\n' "$COMMIT"
  printf -- '- Built: %s (features: %s)\n' "$(date -u +%Y-%m-%dT%H:%M:%SZ)" "$FEATURES"
  printf -- '- Binary: `%s/bin/%s`\n' "$ROOT" "$EXE"
  printf -- '- Project schema: `%s/bin/project.schema.json`\n\n' "$ROOT"
  printf 'Every command takes `--json` (machine output on stdout, logs on stderr). Exit codes:\n'
  printf '0 ok · 1 validation/QA error · 2 usage · 3 tool/dependency · 4 internal.\n\n'
  printf '## Contents\n\n1. Workflow\n2. Commands\n3. Project format\n4. Names (templates, transitions, effects, …)\n5. Tools on the build machine\n\n'

  printf '## 1. Workflow\n\n'
  "$B" guide | demote

  printf '\n## 2. Commands\n\n'
  printf '### `cutline`\n\n```text\n'
  "$B" --help
  printf '```\n\n'
  for c in $("$B" --help | awk '/^Commands:/ { on = 1; next } /^[^ ]/ { on = 0 } on && NF { print $1 }' | grep -v '^help$'); do
    help_section "###" "$c"
  done

  printf '## 3. Project format\n\n'
  demote docs/PROJECT_FORMAT.md

  printf '\n## 4. Names\n\nFrom `cutline templates list`:\n\n```text\n'
  "$B" templates list
  printf '```\n\n'

  printf '## 5. Tools on the build machine\n\nFrom `cutline doctor` when this manual was built (run it again to check the current machine):\n\n```text\n'
  "$B" doctor 2>&1 || true
  printf '```\n'
} > "$M"

rm -rf bin
mv "$STAGE" bin
echo "✔ bin/$EXE ($VERSION, $COMMIT)"
echo "✔ bin/CUTLINE_MANUAL.md ($(wc -l < bin/CUTLINE_MANUAL.md | tr -d ' ') lines), bin/project.schema.json, bin/assets/"
