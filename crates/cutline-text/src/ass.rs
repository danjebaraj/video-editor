//! ASS (Advanced SubStation Alpha) document generation and escaping.

use std::fmt::Write;

/// `#RRGGBB` (or `0xRRGGBB`, optional alpha `#RRGGBBAA`) → ASS `&HAABBGGRR` (alpha 00 = opaque).
pub fn color(c: &str) -> String {
    let h = c.trim().trim_start_matches('#').trim_start_matches("0x");
    let p = |i: usize| h.get(i..i + 2).and_then(|x| u8::from_str_radix(x, 16).ok()).unwrap_or(255);
    let (r, g, b) = (p(0), p(2), p(4));
    let a = if h.len() >= 8 { 255 - p(6) } else { 0 };
    format!("&H{a:02X}{b:02X}{g:02X}{r:02X}")
}

/// Inline override color (`\c&HBBGGRR&`).
pub fn color_tag(c: &str) -> String {
    let full = color(c);
    format!("&H{}&", &full[4..])
}

/// Escape user text for an ASS Dialogue line: braces would open override blocks and `\N`,
/// `\n`, `\h` are control sequences. Backslashes get a word joiner (U+2060) so they never form
/// escapes; braces become their escaped forms; real newlines become `\N`.
pub fn escape_text(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    for ch in s.chars() {
        match ch {
            '\\' => out.push_str("\\\u{2060}"),
            '{' => out.push_str("\\{"),
            '}' => out.push_str("\\}"),
            '\n' => out.push_str("\\N"),
            '\r' => {}
            c => out.push(c),
        }
    }
    out
}

/// ASS timestamp `H:MM:SS.cc`.
pub fn ts(secs: f64) -> String {
    let cs = (secs.max(0.0) * 100.0).round() as i64;
    format!("{}:{:02}:{:02}.{:02}", cs / 360000, (cs / 6000) % 60, (cs / 100) % 60, cs % 100)
}

#[derive(Debug, Clone, PartialEq)]
pub struct Style {
    pub name: String,
    pub font: String,
    pub size: f64,
    pub primary: String,
    pub secondary: String,
    pub outline_color: String,
    pub back: String,
    pub bold: bool,
    pub italic: bool,
    pub spacing: f64,
    /// 1 = outline + shadow, 3 = opaque box.
    pub border_style: u8,
    pub outline: f64,
    pub shadow: f64,
    pub alignment: u8,
    pub margin_l: i32,
    pub margin_r: i32,
    pub margin_v: i32,
}

impl Style {
    pub fn new(name: &str, font: &str, size: f64) -> Self {
        Self {
            name: name.into(),
            font: font.into(),
            size,
            primary: "#FFFFFF".into(),
            secondary: "#FFC400".into(),
            outline_color: "#000000".into(),
            back: "#00000080".into(),
            bold: false,
            italic: false,
            spacing: 0.0,
            border_style: 1,
            outline: 0.0,
            shadow: 0.0,
            alignment: 5,
            margin_l: 0,
            margin_r: 0,
            margin_v: 0,
        }
    }
    fn line(&self) -> String {
        format!(
            "Style: {},{},{},{},{},{},{},{},{},0,0,100,100,{},0,{},{},{},{},{},{},{},1",
            self.name,
            self.font,
            fmtn(self.size),
            color(&self.primary),
            color(&self.secondary),
            color(&self.outline_color),
            color(&self.back),
            if self.bold { -1 } else { 0 },
            if self.italic { -1 } else { 0 },
            fmtn(self.spacing),
            self.border_style,
            fmtn(self.outline),
            fmtn(self.shadow),
            self.alignment,
            self.margin_l,
            self.margin_r,
            self.margin_v
        )
    }
}

fn fmtn(v: f64) -> String {
    let s = format!("{:.2}", v);
    s.trim_end_matches('0').trim_end_matches('.').to_string()
}

#[derive(Debug, Clone, PartialEq)]
pub struct Event {
    pub layer: i32,
    pub start: f64,
    pub end: f64,
    pub style: String,
    /// Raw text including override blocks (already escaped where needed).
    pub text: String,
}

#[derive(Debug, Clone, Default)]
pub struct Doc {
    pub width: u32,
    pub height: u32,
    pub styles: Vec<Style>,
    pub events: Vec<Event>,
}

impl Doc {
    pub fn new(width: u32, height: u32) -> Self {
        Self { width, height, styles: vec![], events: vec![] }
    }
    pub fn add_style(&mut self, s: Style) {
        if !self.styles.iter().any(|x| x.name == s.name) {
            self.styles.push(s);
        }
    }
    pub fn render(&self) -> String {
        let mut s = String::new();
        let _ = writeln!(s, "[Script Info]\n; generated by cutline\nScriptType: v4.00+\nPlayResX: {}\nPlayResY: {}\nWrapStyle: 2\nScaledBorderAndShadow: yes\nYCbCr Matrix: TV.709\n", self.width, self.height);
        let _ = writeln!(s, "[V4+ Styles]\nFormat: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding");
        for st in &self.styles {
            let _ = writeln!(s, "{}", st.line());
        }
        let _ =
            writeln!(s, "\n[Events]\nFormat: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text");
        let mut ev = self.events.clone();
        ev.sort_by(|a, b| a.start.partial_cmp(&b.start).unwrap().then(a.layer.cmp(&b.layer)));
        for e in &ev {
            let _ = writeln!(
                s,
                "Dialogue: {},{},{},{},,0,0,0,,{}",
                e.layer,
                ts(e.start),
                ts(e.end),
                e.style,
                e.text.replace('\n', "\\N")
            );
        }
        s
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn colors() {
        assert_eq!(color("#FFC400"), "&H0000C4FF");
        assert_eq!(color("#00000080"), "&H7F000000");
        assert_eq!(color_tag("#FF0000"), "&H0000FF&");
    }
    #[test]
    fn escaping() {
        assert_eq!(escape_text("a{b}c"), "a\\{b\\}c");
        assert_eq!(escape_text("C:\\New folder"), "C:\\\u{2060}New folder");
        assert_eq!(escape_text("one\ntwo"), "one\\Ntwo");
        assert_eq!(escape_text("50%, yes; [ok]"), "50%, yes; [ok]");
        // a literal "\N" typed by the user must not become a line break
        assert!(!escape_text("\\N").contains("\\N"));
    }
    #[test]
    fn times() {
        assert_eq!(ts(0.0), "0:00:00.00");
        assert_eq!(ts(62.345), "0:01:02.35");
        assert_eq!(ts(3723.5), "1:02:03.50");
    }
    #[test]
    fn doc_render() {
        let mut d = Doc::new(1080, 1920);
        d.add_style(Style::new("T", "Anton", 120.0));
        d.events.push(Event { layer: 0, start: 1.0, end: 2.0, style: "T".into(), text: "Hi, there".into() });
        let s = d.render();
        assert!(
            s.contains("PlayResY: 1920")
                && s.contains("Style: T,Anton,120,")
                && s.contains("Dialogue: 0,0:00:01.00,0:00:02.00,T,,0,0,0,,Hi, there")
        );
    }
}
